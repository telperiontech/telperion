/**
 * Starts (or refreshes) the frpc tunnel that publishes every osw dev server through frp-gate:
 * the shell at https://<base> and each remote at https://<name>.<base>, where
 * <base> = <DEV_DEVICE>.<FRP_GATE_USER>.<OSW_DEV_ZONE>. The server, zone and identity come from
 * .workspace/dev.env (given by the frp-gate admin); none of them is committed.
 *
 * The proxy list comes from the Nx workspace (dev-apps.ts), so it is written to
 * apps/osw/.mediator/frpc.toml (gitignored) on every run and frpc is recreated to load it.
 * Run it again after adding a remote. The file holds only {{ .Envs.X }} placeholders: the
 * client image prints its config at start, and the token must never appear literally.
 *
 * Usage: nx run osw:mediator [--args=--dry-run]
 *   --dry-run  write frpc.toml and validate the compose file, without starting frpc
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
// Relative: plain `node -r @swc-node/register` does not apply tsconfig paths
import { DEV_ENV_FILE, DevEnvError, readDevIdentity } from '../kit/build/src/dev/identity';
import { COMPOSE, OSW_ROOT } from './compose';
import { devApps, devUrl, type DevApp } from './dev-apps';

const FRPC_TOML = join(OSW_ROOT, '.mediator/frpc.toml');
const BASE = '{{ .Envs.DEV_DEVICE }}.{{ .Envs.FRP_GATE_USER }}.{{ .Envs.OSW_DEV_ZONE }}';

function proxy(app: DevApp): string {
	return [
		`# ${app.project}`,
		'[[proxies]]',
		`name = "${app.proxy}-{{ .Envs.DEV_DEVICE }}"`,
		'type = "http"',
		'localIP = "host.docker.internal"',
		`localPort = ${app.port}`,
		`customDomains = ["${app.subdomain ? `${app.subdomain}.` : ''}${BASE}"]`,
		// frps drops the gateway's header; the dev servers are only reached over https
		'requestHeaders.set.x-forwarded-proto = "https"',
	].join('\n');
}

function frpcToml(apps: DevApp[]): string {
	return `# Generated by \`nx run osw:mediator\` (apps/osw/scripts/mediator.ts) from the Nx workspace. Do not edit.
#
# Only {{ .Envs.X }} placeholders: values come from ${DEV_ENV_FILE} (env_file in docker-compose.mediator.yml).
# Every name below is public on the internet; only the osw dev servers are tunnelled.
#
# Proxy names are osw-<app>-<device>: frps prefixes them with the user only, and one developer runs
# clients like this on several devices and for several projects under the same frp-gate user.

serverAddr = "{{ .Envs.FRP_GATE_SERVER_ADDR }}"
serverPort = {{ .Envs.FRP_GATE_SERVER_PORT }}
user = "{{ .Envs.FRP_GATE_USER }}"
metadatas.token = "{{ .Envs.FRP_GATE_TOKEN }}"

transport.heartbeatInterval = 15
transport.heartbeatTimeout = 60

log.to = "console"
log.level = "info"

${apps.map(proxy).join('\n\n')}
`;
}

async function main(): Promise<void> {
	const identity = readDevIdentity();

	if (!identity.hasToken) throw new DevEnvError(`FRP_GATE_TOKEN is empty in ${DEV_ENV_FILE}. Ask the frp-gate admin for your token.`);

	const apps = await devApps();

	mkdirSync(join(OSW_ROOT, '.mediator'), { recursive: true });
	writeFileSync(FRPC_TOML, frpcToml(apps));

	if (process.argv.includes('--dry-run')) {
		// --quiet: plain `config` inlines env_file values, printing the token
		execFileSync('docker', [...COMPOSE, 'config', '--quiet'], { stdio: 'inherit' });
		console.log(`Wrote ${FRPC_TOML} (${apps.length} proxies); compose config is valid. frpc not started (--dry-run).`);

		return;
	}

	// --force-recreate: compose does not notice a changed bind-mounted file, and frpc reads it only at start.
	// --remove-orphans: removes the old auto-proxy gateway container of this project.
	execFileSync('docker', [...COMPOSE, 'up', '-d', '--remove-orphans', '--force-recreate'], { stdio: 'inherit' });

	console.log(`\nfrpc started for ${identity.user} on ${identity.device}. Once \`nx run osw:serve\` runs:`);
	apps.forEach((app) => console.log(`  ${devUrl(identity, app).padEnd(64)} <- localhost:${app.port}`));
	console.log('\nCheck the tunnel with `nx run osw:status`.');
}

main()
	// The Nx daemon connection opened by createProjectGraphAsync keeps the process alive
	.then(() => process.exit(0))
	.catch((error) => {
		console.error(error instanceof DevEnvError ? error.message : error);
		process.exit(1);
	});
